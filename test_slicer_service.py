KEY = 'slicer-test-key-not-a-real-secret'


def binary_stl(vertices=((0, 0, 0), (20, 0, 0), (0, 20, 20))):
    return b'binary stl'.ljust(80, b' ') + struct.pack('<I12fH', 1, 0, 0, 1, *(value for vertex in vertices for value in vertex), 0)


ASCII = b'''solid sample
facet normal 0 0 1
outer loop
vertex 0 0 0
vertex 20 0 0
vertex 0 20 20
endloop
endfacet
endsolid sample
'''


class SlicerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.engine = self.root / 'fake_engine.py'
        self.settings = self.root / 'fullprint.json'
        self.filament = self.root / 'fullfilament.json'
        self.settings.write_text('{}')
        self.filament.write_text('{}')
        self.data = self.root / 'data'
        self.data.mkdir()
        self.config = dict({'owner_id':10001}, **{'api_key': KEY, 'orca_command': [sys.executable, str(self.engine)],
            'settings_files': [str(self.settings)], 'filament_file': str(self.filament),
            'data_dir': str(self.data), 'state_dir': str(self.root / 'state'), 'timeout_seconds': 2,
            'bed_size': [220, 220, 250]})
        self.write_engine()
        self.server = None

    def tearDown(self):
        if self.server:
            self.server.slicer.stop()
            self.server.shutdown()
            self.server.server_close()
            self.thread.join(2)
        self.temp.cleanup()

    def write_engine(self, behavior='success'):
        child_code = "import time,pathlib;time.sleep(.6);pathlib.Path(" + repr(str(self.root / 'escaped-child')) + ").touch()"
        extra = {
            'success': '',
            'fail': 'sys.exit(7)',
            'bad_result': "(out/'result.json').write_text('{broken');sys.exit(0)",
            'result_error': "(out/'result.json').write_text(json.dumps({'return_code':-5}));sys.exit(0)",
            'multiple': "(out/'plate_2.gcode').write_text('; OrcaSlicer\\nG90\\n')",
            'oversize': f"(out/'plate_1.gcode').touch();os.truncate(out/'plate_1.gcode',{MAX_OUTPUT + 1});sys.exit(0)",
            'sleep': 'time.sleep(10)',
            'child': "child=subprocess.Popen([sys.executable,'-c'," + repr(child_code) + "]);time.sleep(10)",
            'hold': f"pathlib.Path({str(self.root/'entered')!r}).touch();\nwhile not pathlib.Path({str(self.root/'release')!r}).exists(): time.sleep(.01)",
        }[behavior]
        self.engine.write_text("""import json,os,pathlib,subprocess,sys,time
args=sys.argv[1:]
out=pathlib.Path(args[args.index('--outputdir')+1]);out.mkdir(exist_ok=True)
""" + extra + """
(out/'plate_1.gcode').write_text('; generated by OrcaSlicer\\n; estimated printing time (normal mode) = 1h 2m 3s\\n; filament used [g] = 12.34\\nG90\\nM104 S240\\n')
(out/'result.json').write_text(json.dumps({'return_code':0}))
""")

    def start_server(self):
        self.server = SlicerHTTPServer(('127.0.0.1', 0), Slicer(self.config))
        self.thread = threading.Thread(target=self.server.serve_forever, kwargs={'poll_interval': .01}, daemon=True)
        self.thread.start()
        return self.server.server_address[1]

    def request(self, method, path, body=None, key=KEY, headers=None):
        connection = http.client.HTTPConnection('127.0.0.1', self.server.server_address[1], timeout=5)
        values = {'X-Slicer-Key': key}
        values.update(headers or {})
        connection.request(method, path, body=body, headers=values)
        response = connection.getresponse()
        result = response.status, dict(response.getheaders()), response.read()
        connection.close()
        return result

    def test_binary_and_ascii_stl_are_geometry_validated(self):
        for payload in [binary_stl(), ASCII, b'solid binary'.ljust(80, b' ') + binary_stl()[80:]]:
            source = self.root / 'model.stl'
            source.write_bytes(payload)
            self.assertEqual(validate_stl(source), {'triangles': 1, 'dimensions_mm': [20.0, 20.0, 20.0]})

    def test_invalid_finite_empty_truncated_and_non_stl_are_rejected(self):
        invalid = [b'', b'PK\x03\x04not-a-3mf', binary_stl()[:-1], b'solid empty\nendsolid empty',
            binary_stl(((0, 0, 0), (math.inf, 0, 0), (0, 20, 20))),
            ASCII.replace(b'vertex 20 0 0', b'vertex nan 0 0'),
            ASCII.replace(b'vertex 20 0 0\n', b''),
            ASCII.replace(b'endfacet\n', b''), ASCII.replace(b'endsolid sample\n', b'')]
        for payload in invalid:
            with self.subTest(payload=payload[:20]):
                source = self.root / 'model.stl';source.write_bytes(payload)
                with self.assertRaises(SliceError):
                    validate_stl(source)

    def test_geometry_limits_and_no_silent_scaling(self):
        source = self.root / 'model.stl'
        source.write_bytes(binary_stl())
        with self.assertRaises(SliceError) as caught:
            validate_stl(source, max_triangles=0)
        self.assertEqual(caught.exception.code, 'too_many_triangles')
        source.write_bytes(binary_stl(((0, 0, 0), (500, 0, 0), (0, 20, 20))))
        with self.assertRaises(SliceError) as caught:
            validate_stl(source)
        self.assertEqual(caught.exception.code, 'oversize')

    def test_health_authentication_and_readiness(self):
        self.start_server()
        self.assertEqual(self.request('GET', '/health', key='wrong')[0], 401)
        status, _, body = self.request('GET', '/health')
        self.assertEqual(status, 200)
        self.assertEqual(json.loads(body), {'ready': True, 'busy': False, 'engine': 'OrcaSlicer', 'material': 'PETG'})
        self.settings.unlink()
        self.assertEqual(self.request('GET', '/health')[0], 503)
        self.assertEqual(self.request('POST', '/slice', binary_stl())[0], 503)

    def test_unreadable_bundle_reports_unavailable_instead_of_dropping_request(self):
        self.start_server()
        with patch('slicer_service.Path.stat', side_effect=PermissionError('unreadable bundle')):
            status, _, body = self.request('GET', '/health')
            self.assertEqual(status, 503)
            self.assertEqual(json.loads(body)['error'], 'configuration')
            self.assertFalse(json.loads(body)['ready'])
