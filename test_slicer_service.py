    def test_busy_rejects_a_second_job_without_starting_it(self):
        self.write_engine('hold');self.start_server()
        result = []
        worker = threading.Thread(target=lambda: result.append(self.request('POST', '/slice', binary_stl())))
        worker.start()
        try:
            deadline = time.monotonic() + 2
            while not (self.root / 'entered').exists() and time.monotonic() < deadline:
                time.sleep(.01)
            self.assertTrue((self.root / 'entered').exists())
            self.assertTrue(json.loads(self.request('GET', '/health')[2])['busy'])
            status, _, body = self.request('POST', '/slice', binary_stl())
            self.assertEqual((status, json.loads(body)['error']), (503, 'busy'))
        finally:
            (self.root / 'release').touch();worker.join(3)
        self.assertEqual(result[0][0], 200)

    def test_subprocess_failures_never_return_partial_gcode(self):
        self.start_server()
        for mode, expected, code in [('fail', 422, 'invalid_model'), ('result_error', 422, 'invalid_model'),
                ('bad_result', 502, 'invalid_engine_result'), ('multiple', 502, 'invalid_engine_result'),
                ('oversize', 502, 'output_too_large')]:
            with self.subTest(mode=mode):
                self.write_engine(mode)
                status, _, body = self.request('POST', '/slice', binary_stl())
                self.assertEqual((status, json.loads(body)['error']), (expected, code))
                self.assertEqual(list((self.root / 'state').iterdir()), [])

    def test_external_timeout_kills_process_group_and_releases_slot(self):
        self.write_engine('child');self.config['timeout_seconds'] = .2;self.start_server()
        started = time.monotonic()
        status, _, body = self.request('POST', '/slice', binary_stl())
        self.assertEqual((status, json.loads(body)['error']), (504, 'slice_timeout'))
        self.assertLess(time.monotonic() - started, 3)
        time.sleep(.7)
        self.assertFalse((self.root / 'escaped-child').exists(), 'grandchild escaped the process group')
        self.write_engine('success')
        self.assertEqual(self.request('POST', '/slice', binary_stl())[0], 200)

    def test_service_stop_terminates_active_engine_without_returning_gcode(self):
        self.write_engine('hold');self.start_server()
        result = []
        worker = threading.Thread(target=lambda: result.append(self.request('POST', '/slice', binary_stl())))
        worker.start()
        deadline = time.monotonic() + 2
        while not (self.root / 'entered').exists() and time.monotonic() < deadline:
            time.sleep(.01)
        self.assertTrue((self.root / 'entered').exists())
        with self.server.slicer.process_lock:
            process = self.server.slicer.process
        self.assertIsNotNone(process)
        self.server.slicer.stop()
        self.assertIsNotNone(process.poll(), 'active engine survived service stop')
        worker.join(2)
        self.assertFalse(worker.is_alive())
        self.assertEqual((result[0][0], json.loads(result[0][2])['error']), (503, 'unavailable'))
        # Receiving the error body does not join the server handler: its
        # finally block may still be releasing the slot on another CPU.
        # Wait for that actual synchronization event, not a scheduling delay.
        released = self.server.slicer.slot.acquire(timeout=2)
        try:
            self.assertTrue(released, 'handler did not release the slicing slot after stop')
        finally:
            if released:
                self.server.slicer.slot.release()

    def test_request_rejection_does_not_invoke_engine(self):
        self.start_server()
        for body, headers, status in [(b'PK\x03\x04fake', {}, 422), (b'anything', {'Content-Length': str(MAX_INPUT + 1)}, 413),
                (b'', {'Content-Length': '0'}, 413), (b'anything', {'Transfer-Encoding': 'chunked'}, 411)]:
            self.assertEqual(self.request('POST', '/slice', body, headers=headers)[0], status)
        self.assertEqual(self.request('POST', '/not-slice', binary_stl())[0], 404)
        self.assertEqual(self.request('POST', '/slice', binary_stl(), key='wrong')[0], 401)

